export function padFaq(faq, min = 250, max = 450, extras = []) {
  const pool = [...extras, ...TECH_POOL];
  return faq.map((f) => {
    const answer = Array.isArray(f.answer) ? [...f.answer] : [String(f.answer || '')];
    let i = 0;
    while (answer.join('').length < min && i < 20) {
      answer.push(pool[i % pool.length]);
      i += 1;
    }
    return { ...f, answer };
  });
}
